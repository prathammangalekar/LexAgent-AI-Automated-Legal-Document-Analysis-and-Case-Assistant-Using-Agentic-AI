"""Agent 6: Legal Drafting Agent.

Generates formal legal documents in Indian legal formatting:
Legal Notices, Replies to Legal Notices, Case Summaries, Legal Research Memos,
and Complaint Drafts.
Embeds verified statutory citations, structured placeholders, assumptions,
and mandatory advocate review disclaimers.
"""

from __future__ import annotations

import datetime
from typing import List, Dict, Any, Optional
from lexagent_ai.models.schemas import (
    DraftType,
    GeneratedDraft,
    ExtractedDocument,
    DocumentAnalysisResult,
    LegalResearchResult,
    LegalReasoningResult
)


class LegalDraftingAgent:
    """Agent generating legally rigorous drafts in Indian jurisdictional format."""

    MANDATORY_DISCLAIMER = (
        "CONFIDENTIAL & PRIVILEGED DRAFT — FOR LEGAL PROFESSIONAL REVIEW ONLY.\n"
        "THIS INSTRUMENT IS GENERATED BY LEXAGENT AI FOR ASSISTIVE PURPOSES. "
        "IT DOES NOT CONSTITUTE A FINALIZED LEGAL DOCUMENT AND CANNOT BE ISSUED, "
        "EXECUTED, OR FILED BEFORE ANY COURT, TRIBUNAL, OR AUTHORITY WITHOUT INDEPENDENT "
        "VERIFICATION, SCRUTINY, AND SIGNATURE BY AN ADVOCATE ENROLLED UNDER THE ADVOCATES ACT, 1961."
    )

    def generate_draft(
        self,
        draft_type: DraftType,
        case_title: str,
        facts_summary: str,
        claimant_name: Optional[str] = None,
        respondent_name: Optional[str] = None,
        statutory_grounds: Optional[List[str]] = None,
        precedents: Optional[List[str]] = None
    ) -> GeneratedDraft:
        """Constructs a structured legal draft conforming to Indian legal conventions."""
        today_str = datetime.date.today().strftime("%d %B %Y")
        c_name = claimant_name or "[CLIENT / CLAIMANT FULL NAME]"
        r_name = respondent_name or "[OPPOSITE PARTY / RESPONDENT FULL NAME]"
        statutes = statutory_grounds or ["Section 73 and 74, Indian Contract Act, 1872"]
        cases = precedents or ["Kailash Nath Associates v. DDA (2015) 4 SCC 136"]

        placeholders: List[str] = []
        assumptions: List[str] = []

        if claimant_name is None:
            placeholders.append("[CLIENT / CLAIMANT FULL NAME]")
            placeholders.append("[CLIENT REGISTERED ADDRESS]")
        if respondent_name is None:
            placeholders.append("[OPPOSITE PARTY FULL NAME]")
            placeholders.append("[OPPOSITE PARTY ADDRESS]")

        placeholders.extend(["[DEMAND AMOUNT IN NUMBERS & WORDS]", "[NOTICE PERIOD E.G. 15 DAYS]", "[ADVOCATE NAME & ENROLLMENT NO]"])
        assumptions.append("Assumes that the claimant has not waived contractual rights through written correspondence.")
        assumptions.append("Assumes that the dispute falls within the territorial and pecuniary jurisdiction of the designated forum.")

        if draft_type == DraftType.LEGAL_NOTICE:
            title = f"FORMAL LEGAL NOTICE UNDER INSTRUCTIONS OF {c_name.upper()}"
            caption = f"DEMAND NOTICE REGARDING BREACH OF CONTRACT AND UNLAWFUL WITHHOLDING OF DUES"
            formal_body = (
                f"WITHOUT PREJUDICE\n"
                f"REGISTERED A.D. / SPEED POST / E-MAIL\n\n"
                f"Date: {today_str}\n\n"
                f"TO,\n"
                f"{r_name}\n"
                f"[OPPOSITE PARTY ADDRESS]\n\n"
                f"FROM,\n"
                f"[ADVOCATE NAME, ADVOCATE ON RECORD]\n"
                f"[CHAMBERS ADDRESS / ENROLLMENT NO. KAR/XXXX/YYYY]\n\n"
                f"SUBJECT: LEGAL NOTICE UNDER SECTION 73 OF THE INDIAN CONTRACT ACT, 1872 FOR WRONGFUL WITHHOLDING "
                f"OF DUES AND PURPORTED ENFORCEMENT OF UNLAWFUL PENAL CLAUSES.\n\n"
                f"SIR / MADAM,\n\n"
                f"Under instructions from and on behalf of my client, {c_name} (hereinafter referred to as 'My Client'), "
                f"I hereby serve upon you this formal Legal Notice as follows:\n\n"
                f"1. That My Client entered into an agreement dated [DATE OF AGREEMENT] with you, the Noticee, for the provision "
                f"of [NATURE OF SERVICES / DELIVERABLES], on agreed commercial terms.\n\n"
                f"2. That My Client duly performed their obligations with utmost professional diligence, and delivered all "
                f"agreed milestones as evidenced by contemporaneous project records and correspondence.\n\n"
                f"3. That despite complete substantial performance, you, the Noticee, have wrongfully, illegally, and unilaterally "
                f"withheld the sum of [DEMAND AMOUNT IN NUMBERS & WORDS], purporting to invoke an impermissible penal deduction.\n\n"
                f"4. That in law, under Section 74 of the Indian Contract Act, 1872 and the authoritative decision of the Hon'ble "
                f"Supreme Court of India in Kailash Nath Associates v. Delhi Development Authority (2015) 4 SCC 136, compensation "
                f"cannot be forfeited or deducted as liquidated damages without proof of actual loss suffered. Your unilateral "
                f"withholding is an arbitrary penalty unsupported by any demonstrable financial injury.\n\n"
                f"5. That any post-contractual non-compete or restraint of trade asserted by you is completely void ab initio "
                f"under Section 27 of the Indian Contract Act, 1872 and the law declared in Percept D'Mark v. Zaheer Khan (2006) 4 SCC 227.\n\n"
                f"WHEREFORE, I hereby call upon you, the Noticee, to remit the outstanding sum of [DEMAND AMOUNT IN NUMBERS & WORDS] "
                f"along with interest @ 18% per annum from the due date within fifteen (15) days of receipt of this notice, failing "
                f"which My Client has given me peremptory instructions to initiate appropriate legal proceedings before the "
                f"competent court or arbitral tribunal, holding you liable for all costs and consequences.\n\n"
                f"Yours faithfully,\n\n"
                f"___________________________\n"
                f"[ADVOCATE NAME]\n"
                f"Counsel for {c_name}"
            )

        elif draft_type == DraftType.NOTICE_REPLY:
            title = f"REPLY TO LEGAL NOTICE DATED [DATE OF RECEIVED NOTICE]"
            caption = f"REPLY ON BEHALF OF {c_name.upper()} REFUTING UNSUBSTANTIATED CLAIMS"
            formal_body = (
                f"WITHOUT PREJUDICE\n\n"
                f"Date: {today_str}\n\n"
                f"TO,\n"
                f"[ADVOCATE FOR OPPOSITE PARTY]\n"
                f"[ADDRESS]\n\n"
                f"RE: REPLY ON BEHALF OF {c_name} TO YOUR NOTICE DATED [DATE OF NOTICE] SENT ON BEHALF OF {r_name}.\n\n"
                f"SIR,\n\n"
                f"Under instructions from and on behalf of my client, {c_name}, I place on record this formal reply:\n\n"
                f"1. That all allegations, imputations, and monetary claims contained in your notice under reply are false, "
                f"frivolous, misconceived, and vehemently denied in toto, save and except what is specifically admitted herein.\n\n"
                f"2. That the purported restrictive covenants and penalty clauses sought to be enforced by your client are "
                f"wholly unconstitutional and void under Section 27 and Section 74 of the Indian Contract Act, 1872.\n\n"
                f"3. That your client has suppressed material facts regarding their own defaults that prevented timely execution. "
                f"Under the doctrine of prevention, your client cannot take advantage of its own wrong.\n\n"
                f"In the premises aforesaid, your client is advised to immediately withdraw the baseless notice under reply.\n\n"
                f"___________________________\n"
                f"[ADVOCATE NAME]\n"
                f"Counsel for {c_name}"
            )

        elif draft_type == DraftType.LEGAL_RESEARCH_MEMO:
            title = f"LEGAL RESEARCH MEMORANDUM: {case_title.upper()}"
            caption = f"IN-DEPTH MEMORANDUM ON INDIAN STATUTORY PROVISIONS AND APPLICABLE JUDICIAL PRECEDENTS"
            formal_body = (
                f"CONFIDENTIAL ATTORNEY-CLIENT WORK PRODUCT\n\n"
                f"MEMORANDUM\n\n"
                f"TO: Senior Legal Counsel\n"
                f"FROM: LexAgent AI Legal Research Division\n"
                f"DATE: {today_str}\n"
                f"MATTER: {case_title}\n\n"
                f"I. QUESTIONS PRESENTED:\n"
                f"1. Whether the contractual clauses in dispute withstand scrutiny under Indian public policy and the Indian Contract Act?\n"
                f"2. What evidentiary hurdles exist under the Bharatiya Sakshya Adhiniyam, 2023 / Indian Evidence Act, 1872?\n\n"
                f"II. EXECUTIVE SUMMARY OF LEGAL POSITION:\n"
                f"Indian jurisprudence strictly prohibits post-termination restraints of trade under Section 27 of the Indian Contract Act. "
                f"Furthermore, liquidated damages clauses under Section 74 require proof of reasonable compensation where loss is quantifiable.\n\n"
                f"III. STATUTORY ANALYSIS:\n"
                f"• {', '.join(statutes)}\n\n"
                f"IV. JUDICIAL AUTHORITIES & BINDING RATIOS:\n"
                f"• {', '.join(cases)}\n\n"
                f"V. STRATEGIC RECOMMENDATIONS:\n"
                f"1. Focus preliminary pleadings on the statutory invalidity of the penalty provisions.\n"
                f"2. Ensure all electronic communications are accompanied by an appropriate electronic evidence affidavit.\n"
            )

        else:
            # Case Summary / Complaint draft
            title = f"COMPREHENSIVE CASE SUMMARY: {case_title.upper()}"
            caption = f"FACTUAL CHRONOLOGY AND LEGAL ISSUES BRIEF"
            formal_body = (
                f"CASE SUMMARY & LITIGATION BRIEF\n\n"
                f"Case Title: {case_title}\n"
                f"Date of Preparation: {today_str}\n"
                f"Parties Involved: {c_name} v. {r_name}\n\n"
                f"1. FACTUAL MATRIX:\n{facts_summary}\n\n"
                f"2. PRIMARY LEGAL ISSUES:\n"
                f"• Issue 1: Enforceability of contractual covenants under Section 27 & 74, Indian Contract Act.\n"
                f"• Issue 2: Admissibility of secondary digital evidence under BSA 2023 / IEA 1872.\n\n"
                f"3. GOVERNING AUTHORITIES:\n"
                f"{chr(10).join('• ' + s for s in statutes)}\n"
                f"{chr(10).join('• ' + c for c in cases)}\n\n"
                f"4. LITIGATION STRENGTHS & VULNERABILITIES:\n"
                f"• Strong defense against injunctive relief.\n"
                f"• Need documentary proof of actual loss for monetary claims.\n"
            )

        return GeneratedDraft(
            draft_type=draft_type,
            title=title,
            caption_or_subject=caption,
            formal_body=formal_body,
            statutory_grounds_cited=statutes,
            precedents_referenced=cases,
            placeholders=placeholders,
            stated_assumptions=assumptions,
            mandatory_disclaimer=self.MANDATORY_DISCLAIMER
        )
