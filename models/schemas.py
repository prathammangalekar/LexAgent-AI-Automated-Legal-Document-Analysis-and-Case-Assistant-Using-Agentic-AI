"""Pydantic schemas and data contracts for LexAgent AI.

Defines all structured types used across Document Intelligence, Legal Analysis,
Autonomous Research, Case Comparison, Legal Reasoning, Legal Drafting,
Verification/Hallucination Detection, and Report Generation agents.
"""

from __future__ import annotations

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class DocumentCategory(str, Enum):
    """Categories of legal documents."""
    CONTRACT_AGREEMENT = "contract_agreement"
    EMPLOYMENT_AGREEMENT = "employment_agreement"
    NON_DISCLOSURE_AGREEMENT = "non_disclosure_agreement"
    LEASE_LICENSE_DEED = "lease_license_deed"
    COURT_ORDER_JUDGMENT = "court_order_judgment"
    LEGAL_NOTICE = "legal_notice"
    NOTICE_REPLY = "notice_reply"
    WRIT_PETITION_PLAINT = "writ_petition_plaint"
    WRITTEN_STATEMENT = "written_statement"
    AFFIDAVIT = "affidavit"
    STATUTE_ACT = "statute_act"
    UNKNOWN = "unknown"


class ClauseRiskLevel(str, Enum):
    """Risk severity classifications for legal clauses."""
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class CitationVerificationStatus(str, Enum):
    """Validation states for legal citations."""
    VERIFIED = "verified"
    UNVERIFIED = "unverified"
    HALLUCINATED = "hallucinated"
    OUTDATED = "outdated"
    MISQUOTED = "misquoted"


class DraftType(str, Enum):
    """Types of legal drafts generated by the drafting agent."""
    LEGAL_NOTICE = "legal_notice"
    NOTICE_REPLY = "notice_reply"
    CASE_SUMMARY = "case_summary"
    LEGAL_RESEARCH_MEMO = "legal_research_memo"
    COMPLAINT_DRAFT = "complaint_draft"
    CONTRACT_CLAUSE = "contract_clause"
    REPRESENTATION = "representation"


# ---------------------------------------------------------------------------
# Document Intelligence Models
# ---------------------------------------------------------------------------

class ExtractedParty(BaseModel):
    """Legal party extracted from document."""
    name: str = Field(..., description="Name of party or corporate entity")
    role: str = Field(..., description="Role in instrument e.g. Employer, Employee, Licensor, Petitioner, Respondent")
    address: Optional[str] = Field(None, description="Registered or residential address")
    jurisdiction: Optional[str] = Field(None, description="Stated jurisdiction or nationality")


class ExtractedClause(BaseModel):
    """Individual legal clause extracted from document text."""
    clause_id: str = Field(..., description="Identifier e.g. 'Clause 4.2' or 'Section 8'")
    heading: str = Field(..., description="Heading or topic of the clause")
    text: str = Field(..., description="Full verbatim text of the clause")
    page_number: Optional[int] = Field(None, description="Source page number in original document")
    character_span: Optional[tuple[int, int]] = Field(None, description="Character offsets (start, end)")


class ExtractedEntity(BaseModel):
    """Named legal entity, date, monetary value, or statutory reference."""
    entity_type: str = Field(..., description="DATE, AMOUNT, JURISDICTION, COURT, STATUTE, PENALTY, TERM")
    text: str = Field(..., description="Extracted entity string")
    context: Optional[str] = Field(None, description="Surrounding contextual sentence")


class DocumentChunk(BaseModel):
    """Semantic chunk of a legal document for RAG indexing."""
    chunk_id: str = Field(..., description="Unique chunk identifier")
    document_id: str = Field(..., description="Identifier of parent document")
    document_title: str = Field(..., description="Title or filename of parent document")
    section_heading: str = Field(default="General", description="Heading or clause category")
    text: str = Field(..., description="Text content of the chunk")
    page_number: Optional[int] = Field(None, description="Source page number")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Metadata tags")


class ExtractedDocument(BaseModel):
    """Complete structured output from Document Intelligence Agent."""
    document_id: str = Field(..., description="Unique document ID")
    file_name: str = Field(..., description="Original filename")
    category: DocumentCategory = Field(default=DocumentCategory.UNKNOWN)
    title: str = Field(..., description="Detected document title")
    parties: List[ExtractedParty] = Field(default_factory=list)
    effective_date: Optional[str] = Field(None, description="Effective or execution date")
    governing_law: Optional[str] = Field(None, description="Governing law clause")
    jurisdiction_clause: Optional[str] = Field(None, description="Exclusive jurisdiction or seat")
    dispute_resolution: Optional[str] = Field(None, description="Arbitration / litigation provisions")
    clauses: List[ExtractedClause] = Field(default_factory=list)
    key_entities: List[ExtractedEntity] = Field(default_factory=list)
    total_pages: int = Field(default=1)
    word_count: int = Field(default=0)
    full_text: str = Field(..., description="Full raw extracted text")
    chunks: List[DocumentChunk] = Field(default_factory=list)
    extraction_warnings: List[str] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# Legal Analysis & Understanding Models
# ---------------------------------------------------------------------------

class AnalyzedClause(BaseModel):
    """In-depth legal evaluation of a specific clause."""
    clause_id: str = Field(..., description="Clause identifier")
    clause_title: str = Field(..., description="Clause heading")
    verbatim_text: str = Field(..., description="Verbatim text from source document")
    risk_level: ClauseRiskLevel = Field(..., description="Assessed risk severity")
    risk_category: str = Field(..., description="E.g. Restraint of Trade, Unilateral Indemnity, Liquidated Damages, Ambiguity")
    is_ambiguous: bool = Field(default=False)
    ambiguous_terms: List[str] = Field(default_factory=list, description="Vague or undefined phrases")
    is_contradictory: bool = Field(default=False)
    contradiction_details: Optional[str] = Field(None, description="Specific internal conflict")
    applicable_statute: Optional[str] = Field(None, description="Indian legal section implicated")
    plain_english_summary: str = Field(..., description="Simple explanation for client/non-lawyer")
    legal_interpretation: str = Field(..., description="Formal legal doctrinal analysis")
    recommendation: str = Field(..., description="Drafting advice or mitigation strategy")


class LegalObligation(BaseModel):
    """Obligation or liability assigned to a party."""
    party_name: str
    nature: str = Field(..., description="Affirmative obligation, negative covenant, or indemnity")
    description: str
    trigger_condition: Optional[str] = None
    consequence_of_breach: Optional[str] = None


class DocumentAnalysisResult(BaseModel):
    """Output produced by Legal Understanding and Analysis Agent."""
    document_id: str
    document_type: DocumentCategory
    overall_risk_score: float = Field(..., description="Score from 0.0 (safe) to 1.0 (extreme risk)")
    executive_summary: str = Field(..., description="High-level legal briefing")
    analyzed_clauses: List[AnalyzedClause] = Field(default_factory=list)
    high_risk_clauses: List[AnalyzedClause] = Field(default_factory=list)
    missing_provisions: List[str] = Field(default_factory=list, description="Standard protective clauses absent from document")
    obligations: List[LegalObligation] = Field(default_factory=list)
    factual_assertions: List[str] = Field(default_factory=list, description="Verified facts directly stated in instrument")
    interpretative_inferences: List[str] = Field(default_factory=list, description="AI conclusions distinguished from document facts")
    plain_language_terminology: Dict[str, str] = Field(default_factory=dict, description="Glossary of complex terms used")


# ---------------------------------------------------------------------------
# Legal Research Models
# ---------------------------------------------------------------------------

class VerifiedCitation(BaseModel):
    """Structured legal citation with verification metadata."""
    citation_raw: str = Field(..., description="Raw citation as identified or queried")
    standardized_citation: str = Field(..., description="Normalized legal reporter citation")
    case_or_statute_title: str
    source_type: str = Field(..., description="Statute, Supreme Court Judgment, High Court Judgment")
    year: Optional[int] = None
    court_name: Optional[str] = None
    status: CitationVerificationStatus = Field(default=CitationVerificationStatus.UNVERIFIED)
    official_source_url_or_ref: Optional[str] = None
    ratio_or_rule: str = Field(..., description="Legal principle or binding rule")
    relevant_excerpt: str = Field(..., description="Verified textual excerpt from statute or judgment")
    temporal_validity_note: Optional[str] = Field(None, description="Notes on transition dates (e.g. IPC vs BNS)")


class LegalResearchResult(BaseModel):
    """Output produced by Autonomous Legal Research Agent."""
    research_query: str
    legal_topics: List[str] = Field(default_factory=list)
    applicable_statutes: List[Dict[str, Any]] = Field(default_factory=list, description="Acts and sections identified")
    landmark_judgments: List[VerifiedCitation] = Field(default_factory=list, description="Relevant judicial precedents")
    statutory_provisions_text: Dict[str, str] = Field(default_factory=dict, description="Verbatim text of relevant sections")
    synthesis: str = Field(..., description="Comprehensive legal synthesis of research findings")
    temporal_framework_analysis: str = Field(..., description="Clarification regarding pre/post July 1, 2024 applicability")
    search_confidence: float = Field(default=1.0)


# ---------------------------------------------------------------------------
# Case Comparison Models
# ---------------------------------------------------------------------------

class CaseComparisonItem(BaseModel):
    """Individual case profile in a multi-case comparison."""
    case_id: str
    title: str
    court: str
    year: int
    citation: str
    core_facts: List[str]
    legal_issues_framed: List[str]
    key_statutory_sections: List[str]
    judicial_reasoning: str
    final_disposition: str


class CaseComparisonReport(BaseModel):
    """Output produced by Case Comparison Agent."""
    primary_case_title: str
    comparator_cases: List[CaseComparisonItem] = Field(default_factory=list)
    factual_convergences: List[str] = Field(default_factory=list, description="Identical or analogous factual circumstances")
    factual_distinctions: List[str] = Field(default_factory=list, description="Critical distinguishing facts")
    legal_doctrinal_alignment: str = Field(..., description="How legal principles apply across the compared cases")
    precedent_applicability_score: float = Field(default=0.0, description="Relevance score as binding/persuasive precedent")
    strategic_litigation_insights: List[str] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# Legal Reasoning Models
# ---------------------------------------------------------------------------

class LegalReasoningIssue(BaseModel):
    """Structured IRAC evaluation of an individual legal issue."""
    issue_id: str
    framed_question: str = Field(..., description="Precise question of law or fact to be adjudicated")
    governing_rules: List[str] = Field(..., description="Applicable statutory provisions and judicial ratios")
    claimant_arguments: List[str] = Field(..., description="Strongest arguments in favor of claimant/petitioner")
    respondent_arguments: List[str] = Field(..., description="Strongest defense arguments for respondent/defendant")
    evidence_appraisal: str = Field(..., description="Analysis of supporting documents vs evidentiary gaps")
    irac_synthesis: str = Field(..., description="Application of legal rules to ascertained facts")
    risk_assessment: str = Field(..., description="Probabilistic assessment without claiming judicial certainty")


class LegalReasoningResult(BaseModel):
    """Output produced by Case Reasoning Agent."""
    case_title_or_id: str
    summary_of_ascertained_facts: List[str]
    framed_issues: List[LegalReasoningIssue] = Field(default_factory=list)
    evidentiary_vulnerabilities: List[str] = Field(default_factory=list, description="Missing records or burden of proof issues")
    strategic_legal_interpretations: List[str] = Field(default_factory=list)
    questions_for_counsel: List[str] = Field(default_factory=list, description="Specific queries requiring advocate clarification")


# ---------------------------------------------------------------------------
# Legal Drafting Models
# ---------------------------------------------------------------------------

class GeneratedDraft(BaseModel):
    """Output produced by Legal Drafting Agent."""
    draft_type: DraftType
    title: str
    caption_or_subject: str
    formal_body: str = Field(..., description="Full structured draft formatted in Indian legal convention")
    statutory_grounds_cited: List[str] = Field(default_factory=list)
    precedents_referenced: List[str] = Field(default_factory=list)
    placeholders: List[str] = Field(default_factory=list, description="Missing variables requiring user/lawyer completion")
    stated_assumptions: List[str] = Field(default_factory=list, description="Factual assumptions underpinning the draft")
    mandatory_disclaimer: str = Field(
        default="DRAFT ONLY - FOR INFORMATIONAL ASSISTANCE ONLY. REQUIRES INDEPENDENT ADVOCATE REVIEW AND VERIFICATION PRIOR TO EXECUTION OR FILING.",
        description="Mandatory legal disclaimer"
    )


# ---------------------------------------------------------------------------
# Verification & Hallucination Detection Models
# ---------------------------------------------------------------------------

class VerificationIssue(BaseModel):
    """Specific error or defect detected in agent outputs."""
    issue_type: str = Field(..., description="FABRICATED_CITATION, OUTDATED_LAW, UNSUPPORTED_CLAIM, CONTRADICTION, MISSING_EVIDENCE")
    severity: str = Field(..., description="LOW, MEDIUM, HIGH, FATAL")
    source_agent: str = Field(..., description="Agent that produced the flawed statement")
    flawed_text: str = Field(..., description="Statement identified as incorrect or unsupported")
    reason: str = Field(..., description="Grounds for rejection")
    correction_guidance: str = Field(..., description="Actionable instruction to rectify the error")


class VerificationReport(BaseModel):
    """Output produced by Verification and Hallucination Detection Agent."""
    is_approved: bool = Field(..., description="True if verification passed quality standards")
    confidence_score: float = Field(..., description="Confidence score 0.0 to 1.0")
    total_citations_evaluated: int = Field(default=0)
    verified_citations_count: int = Field(default=0)
    hallucinated_citations: List[str] = Field(default_factory=list)
    outdated_laws_detected: List[str] = Field(default_factory=list)
    unsupported_assertions: List[str] = Field(default_factory=list)
    internal_contradictions: List[str] = Field(default_factory=list)
    issues: List[VerificationIssue] = Field(default_factory=list)
    remediation_required: Optional[str] = Field(None, description="Workflow instruction if rejected")


# ---------------------------------------------------------------------------
# Report Generation Models
# ---------------------------------------------------------------------------

class ComprehensiveLegalReport(BaseModel):
    """Final multi-agent deliverable compiled by Report Generation Agent."""
    report_id: str
    generated_at: str
    report_title: str
    workflow_executed: str
    executive_summary: str
    document_intelligence: Optional[Dict[str, Any]] = None
    legal_clause_analysis: Optional[DocumentAnalysisResult] = None
    legal_research: Optional[LegalResearchResult] = None
    case_reasoning: Optional[LegalReasoningResult] = None
    case_comparison: Optional[CaseComparisonReport] = None
    generated_draft: Optional[GeneratedDraft] = None
    verification_audit: VerificationReport
    actionable_recommendations: List[str] = Field(default_factory=list)
    lawyer_clarification_checklist: List[str] = Field(default_factory=list)
    disclaimer: str = Field(
        default="DISCLAIMER: LexAgent AI is an assistive multi-agent artificial intelligence research system. It does not provide legal advice, does not establish an attorney-client relationship, and cannot substitute for qualified legal counsel licensed by the Bar Council of India.",
        description="Comprehensive regulatory disclaimer"
    )
    pdf_path: Optional[str] = None
    docx_path: Optional[str] = None
